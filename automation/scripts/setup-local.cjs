'use strict';
// One-time local setup for the free-tier stack (n8n self-hosted, Airtable free, Apify free credit, Groq/Ollama, Postiz).
//   node scripts/setup-local.cjs            create .env.local (secrets generated, provider keys left blank) and import into n8n
//   node scripts/setup-local.cjs --no-n8n   only write .env.local
// Re-running keeps existing values in .env.local and re-imports credentials and workflows from it.
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const { spawnSync } = require('child_process');
const { ROOT, ENV_FILE, N8N_BIN, N8N_HOME, loadEnv, parseEnv } = require('./lib.cjs');

const rand = (n) => crypto.randomBytes(n).toString('hex');

function hashPassword(pw) {
  if (pw.length < 10) throw new Error('DASHBOARD_PASSWORD must be at least 10 characters');
  return require('../server/auth.cjs').hashPassword(pw);
}

const TEMPLATE = (v) => `# Generated by scripts/setup-local.cjs. Contains secrets: never commit or share this file.
# ---- You fill these in (see docs/free-stack-setup.md) -------------------------------------------------
AIRTABLE_BASE_ID=${v.AIRTABLE_BASE_ID}
AIRTABLE_WRITE_TOKEN=${v.AIRTABLE_WRITE_TOKEN}
AIRTABLE_READ_TOKEN=${v.AIRTABLE_READ_TOKEN}
APIFY_TOKEN=${v.APIFY_TOKEN}
# LLM + speech-to-text: any OpenAI-compatible endpoint. Defaults target Groq (free tier).
LLM_API_KEY=${v.LLM_API_KEY}
OPENAI_BASE_URL=${v.OPENAI_BASE_URL}
OPENAI_MODEL=${v.OPENAI_MODEL}
OPENAI_STT_MODEL=${v.OPENAI_STT_MODEL}
LLM_JSON_MODE=${v.LLM_JSON_MODE}
# Postiz (publishing). POSTIZ_API_URL is e.g. http://localhost:5000/api/public/v1 (self-hosted) or https://api.postiz.com/public/v1
POSTIZ_API_URL=${v.POSTIZ_API_URL}
POSTIZ_API_KEY=${v.POSTIZ_API_KEY}
POSTIZ_INTEGRATION_ID=${v.POSTIZ_INTEGRATION_ID}
# Faceless video (MoneyPrinterTurbo, installed separately; see docs/free-stack-setup.md). MPT_API_KEY is the [app] api_key in its config.toml.
MPT_DIR=${v.MPT_DIR}
MPT_URL=${v.MPT_URL}
MPT_API_KEY=${v.MPT_API_KEY}
# pexels|pixabay need a free key set in MoneyPrinterTurbo's config.toml; local uses clips in its storage/local_videos (comma separated names)
MPT_VIDEO_SOURCE=${v.MPT_VIDEO_SOURCE}
MPT_LOCAL_MATERIALS=${v.MPT_LOCAL_MATERIALS}
# Public https origin of the dashboard backend (needed so Postiz/Instagram can fetch uploaded videos), e.g. a cloudflared tunnel URL
PUBLIC_BASE_URL=${v.PUBLIC_BASE_URL}

# ---- Generated (leave as is) -----------------------------------------------------------------------------
N8N_PORT=5678
N8N_WEBHOOK_BASE=http://127.0.0.1:5678
N8N_BLOCK_ENV_ACCESS_IN_NODE=false
N8N_INTAKE_TOKEN=${v.N8N_INTAKE_TOKEN}
N8N_INTERNAL_TOKEN=${v.N8N_INTERNAL_TOKEN}
N8N_APPROVAL_TOKEN=${v.N8N_APPROVAL_TOKEN}
ADAPTER_TOKEN=${v.ADAPTER_TOKEN}
SESSION_SECRET=${v.SESSION_SECRET}
DASHBOARD_PASSWORD_HASH=${v.DASHBOARD_PASSWORD_HASH}
AIRTABLE_TABLE=Reels
PORT=8787
HOST=127.0.0.1
NODE_ENV=production
COOKIE_SECURE=false

# ---- Pipeline switches -------------------------------------------------------------------------------------
PUBLISH_ADAPTER=postiz
POSTIZ_ADAPTER_URL=http://127.0.0.1:8790
# Workflow 04 talks to the MoneyPrinterTurbo adapter through its HeyGen-shaped API. avatar/voice ids are labels for it (voice = an Edge TTS voice).
HEYGEN_ENABLED=true
HEYGEN_BASE_URL=http://127.0.0.1:8791
HEYGEN_AVATAR_ID=mpt
HEYGEN_VOICE_ID=en-US-AriaNeural
MIN_VIDEO_SECONDS=3
AUTO_PUBLISH=false
`;

function main() {
  const noN8n = process.argv.includes('--no-n8n');
  const cur = loadEnv();
  const defaults = {
    AIRTABLE_BASE_ID: '', AIRTABLE_WRITE_TOKEN: '', AIRTABLE_READ_TOKEN: '', APIFY_TOKEN: '', LLM_API_KEY: '',
    OPENAI_BASE_URL: 'https://api.groq.com/openai', OPENAI_MODEL: 'openai/gpt-oss-120b', OPENAI_STT_MODEL: 'whisper-large-v3-turbo',
    LLM_JSON_MODE: 'json_schema', POSTIZ_API_URL: '', POSTIZ_API_KEY: '', POSTIZ_INTEGRATION_ID: '', PUBLIC_BASE_URL: '',
    MPT_DIR: '', MPT_URL: 'http://127.0.0.1:8080', MPT_API_KEY: '', MPT_VIDEO_SOURCE: 'pexels', MPT_LOCAL_MATERIALS: '',
    N8N_INTAKE_TOKEN: rand(24), N8N_INTERNAL_TOKEN: rand(24), N8N_APPROVAL_TOKEN: rand(24), ADAPTER_TOKEN: rand(24), SESSION_SECRET: rand(32),
  };
  const v = Object.assign({}, defaults, cur);
  let password = null;
  if (!v.DASHBOARD_PASSWORD_HASH) {
    password = process.env.DASHBOARD_PASSWORD || rand(8);
    v.DASHBOARD_PASSWORD_HASH = hashPassword(password);
  }
  const merged = TEMPLATE(v);
  // Keep any extra keys the user added by hand.
  const extra = Object.keys(cur).filter((k) => !(k in parseEnv(merged)));
  fs.writeFileSync(ENV_FILE, merged + (extra.length ? '\n# ---- Your additions ----\n' + extra.map((k) => k + '=' + cur[k]).join('\n') + '\n' : ''), { mode: 0o600 });
  console.log('Wrote ' + path.relative(ROOT, ENV_FILE));
  if (password) console.log('Dashboard password (shown once; set DASHBOARD_PASSWORD to choose your own before first setup): ' + password);

  if (noN8n) return;
  if (!fs.existsSync(N8N_BIN)) {
    console.error('n8n is not installed. Run: npm run n8n:install');
    process.exit(1);
  }
  const env = Object.assign({}, process.env, { N8N_USER_FOLDER: N8N_HOME, N8N_ENCRYPTION_KEY: v.N8N_ENCRYPTION_KEY || cur.N8N_ENCRYPTION_KEY || '' });
  if (!env.N8N_ENCRYPTION_KEY) {
    env.N8N_ENCRYPTION_KEY = rand(24);
    fs.appendFileSync(ENV_FILE, '\nN8N_ENCRYPTION_KEY=' + env.N8N_ENCRYPTION_KEY + '\n');
  }
  fs.mkdirSync(N8N_HOME, { recursive: true });

  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'n8n-creds-'));
  const header = (id, name, hname, value) => ({ id, name, type: 'httpHeaderAuth', data: { name: hname, value } });
  const creds = [
    { id: 'cred_airtable', name: 'Airtable Personal Access Token', type: 'airtableTokenApi', data: { accessToken: v.AIRTABLE_WRITE_TOKEN || 'unset' } },
    header('cred_apify', 'Apify API Token', 'Authorization', 'Bearer ' + (v.APIFY_TOKEN || 'unset')),
    { id: 'cred_llm', name: 'OpenAI API', type: 'openAiApi', data: { apiKey: v.LLM_API_KEY || 'unset' } },
    header('cred_intake', 'Reels Intake Webhook Auth', 'X-Reels-Token', v.N8N_INTAKE_TOKEN),
    header('cred_internal', 'Reels Internal Webhook Auth', 'X-Reels-Token', v.N8N_INTERNAL_TOKEN),
    header('cred_approval', 'Reels Approval Webhook Auth', 'X-Reels-Token', v.N8N_APPROVAL_TOKEN),
    // With the mpt adapter this credential carries the local adapter token, sent as the x-api-key header.
    header('cred_heygen', 'HeyGen API Key', 'x-api-key', v.ADAPTER_TOKEN),
    // With the postiz adapter this credential carries the local adapter token, sent as the Authorization header.
    header('cred_publish', 'Blotato API Key', 'Authorization', v.ADAPTER_TOKEN),
  ];
  const credFile = path.join(tmp, 'credentials.json');
  fs.writeFileSync(credFile, JSON.stringify(creds), { mode: 0o600 });

  const run = (args) => {
    const r = spawnSync(process.execPath, [N8N_BIN, ...args], { env, encoding: 'utf8', cwd: ROOT, timeout: 180000 });
    if (r.status !== 0) { console.error('n8n ' + args.join(' ') + ' failed\n' + (r.stdout || '') + (r.stderr || '')); fs.rmSync(tmp, { recursive: true, force: true }); process.exit(1); }
    return r.stdout;
  };
  console.log('Importing credentials into n8n...');
  run(['import:credentials', '--input=' + credFile]);
  fs.rmSync(tmp, { recursive: true, force: true });

  // The generated JSON references credentials as {id:'REPLACE_ME', name}. Point each reference at the credential imported above (matched
  // by name) and give each workflow a stable id, so re-running this script overwrites instead of duplicating.
  const credIdByName = Object.fromEntries(creds.map((c) => [c.name, c.id]));
  const wfDir = path.join(ROOT, 'n8n');
  const wfTmp = fs.mkdtempSync(path.join(os.tmpdir(), 'n8n-wf-'));
  const wfIds = [];
  for (const f of fs.readdirSync(wfDir).filter((x) => /^0\d-.*\.json$/.test(x)).sort()) {
    const wf = JSON.parse(fs.readFileSync(path.join(wfDir, f), 'utf8'));
    wf.id = 'reels' + f.slice(0, 2) + crypto.createHash('md5').update(f).digest('hex').slice(0, 8);
    for (const n of wf.nodes || []) {
      for (const [type, ref] of Object.entries(n.credentials || {})) {
        if (!credIdByName[ref.name]) throw new Error('Workflow ' + f + ' node "' + n.name + '" uses credential "' + ref.name + '" (' + type + ') that setup does not create');
        ref.id = credIdByName[ref.name];
      }
    }
    const file = path.join(wfTmp, f);
    fs.writeFileSync(file, JSON.stringify(wf));
    console.log('Importing ' + f);
    run(['import:workflow', '--input=' + file]);
    wfIds.push(wf.id);
  }
  fs.rmSync(wfTmp, { recursive: true, force: true });
  console.log('Publishing workflows...');
  for (const id of wfIds) run(['publish:workflow', '--id=' + id]);
  console.log('Done. Start everything with: npm run start:all (restart it if it was already running)');
}

main();
