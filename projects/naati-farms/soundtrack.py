"""NAATI FARMS v2 soundtrack + shared timeline.

The music is a real produced track, "Midnight Funk" (Michael Ramir C., Mixkit #1147, Mixkit Stock Music Free
License; see audio/LICENSES.md). It is edited only on its own bar lines, so every cut stays musical:
    film bars 0-1   = song bars 6-7    (the build, quieter)       -> black & white question
    film bars 2-9   = song bars 8-15   (the drop, an 8-bar phrase) -> colour: the farm, the proofs, the grid
    film bars 10-13 = song bars 48-51 + the song's own ending      -> brand and phone number
The beat grid was fitted to the track (117.9675 BPM; kick attacks sit within 1 ms of it, median).
On top: the farm's own rooster crow (IMG_1593), flock (IMG_1381) and clucks (IMG_1151), and a few real recorded
Mixkit effects, each levelled against the music around it. Master: -14 LUFS, true peak about -3 dBTP before AAC.

This script also writes ../timeline.json: the cue times (film seconds) that src/film.tsx draws on.
Run:  python soundtrack.py        (writes timeline.json and public/soundtrack.wav)
"""
from pathlib import Path
import json
import re
import subprocess
import sys

import librosa
import numpy as np
import soundfile as sf
from scipy.signal import butter, sosfilt

HERE = Path(__file__).resolve().parent
AUD = HERE / 'audio'
FARM = HERE / 'work' / 'audio'
SR = 48000

# ---------- beat grid (measured on the track, see plan.md) ----------
BPM = 117.9675
P = 60 / BPM                 # one beat, s
BAR = 4 * P
BEAT0 = 0.012137             # first beat of the song, s
DUR = 30.0


def song_bar(n):
    return BEAT0 + n * BAR


def bt(bar, beat=0.0):
    """Film time of a bar/beat (film bar 0 starts at t=0 on song bar 6)."""
    return round((bar * 4 + beat) * P, 4)


EDIT_A = (6, 16)             # song bars [6, 16) -> film bars [0, 10)
EDIT_B = 48                  # song bar 48 -> film bar 10, played to the end of the song
SPLICE = bt(10)

# ---------- cue sheet: one source of time for picture and sound ----------
TL = {
    '_': 'Generated by soundtrack.py. Film seconds on the beat grid of "Midnight Funk" (117.9675 BPM). '
         'src/film.tsx draws on these; soundtrack.py hits on these. Edit cues there, then re-run it.',
    'bpm': BPM, 'beat': P, 'bar': BAR, 'duration': DUR,
    # 0-1  black & white title over the build
    'title': [bt(0, 0), bt(0, 1)],               # "NAATI" / "CHICKEN."
    'underline': bt(0, 2),                       # red rule under CHICKEN.
    'real': bt(1, 0),                            # "The real one."
    'whip': bt(1, 3),                            # push-in toward the drop
    # 2  the drop: colour, the gate opens, the flock runs out
    'drop': bt(2, 0), 'outside': bt(2, 1),       # "Raised" / "OUTSIDE."
    # 3  outside: one shot per beat, no text
    'roam': [bt(3, 0), bt(3, 1), bt(3, 2), bt(3, 3)],
    # 4  lively / healthy; the music is filtered down on the last beat and a half
    'lively': bt(4, 0), 'healthy': bt(4, 2), 'dip': bt(4, 2.5),
    # 5  NO / ANTIBIOTICS.
    'no': bt(5, 0), 'antibiotics': bt(5, 1),
    'stop': round(bt(5, 3.5) - .03, 4),          # the track's own stop: silent 11.98-12.18 s (measured) -> black
    # 6  from our farm in Bangalore
    'farmLine': bt(6, 0), 'bangalore': bt(6, 1),
    # 7-8  the whole farm in a grid
    'grid': bt(7, 0), 'gridOut': bt(8, 2),
    # 9  NAATI as a window, push through it
    'mask': bt(9, 0), 'push': bt(9, 2),
    # 10-13  brand, launch, call (song's final phrase and ending)
    'brand': SPLICE, 'wordmark': bt(10, 1), 'farms': bt(10, 2),
    'launch': bt(11, 0), 'cta': bt(12, 0), 'number': bt(12, 1),
    'final': bt(13, 3),                          # the song's last stab
    'end': DUR,
}


# ---------- io ----------
def load(path, offset=0.0, duration=None):
    y, _ = librosa.load(str(path), sr=SR, mono=False, offset=offset, duration=duration)
    y = np.atleast_2d(y)
    if y.shape[0] == 1:
        y = np.vstack([y, y])
    return y.T.astype(np.float64)


def fade(x, fin=.003, fout=.003):
    n = len(x)
    a, b = int(fin * SR), int(fout * SR)
    env = np.ones(n)
    if a:
        env[:a] = np.linspace(0, 1, a)
    if b:
        env[n - b:] = np.minimum(env[n - b:], np.linspace(1, 0, b))
    return x * env[:, None]


def filt(x, kind, f, order=4):
    return sosfilt(butter(order, f, kind, fs=SR, output='sos'), x, axis=0)


def rms_db(x):
    return 20 * np.log10(np.sqrt(np.mean(x ** 2)) + 1e-12)


def anchor(x, how):
    """Sample offset inside a sound that should land on the cue: its attack ('onset') or loudest moment ('peak')."""
    env = np.abs(x).max(1)
    sm = np.convolve(env, np.ones(int(.004 * SR)) / int(.004 * SR), 'same')
    if how == 'peak':
        return int(np.argmax(np.convolve(env, np.ones(int(.03 * SR)) / int(.03 * SR), 'same')))
    if how == 'onset':
        return int(np.argmax(sm > .3 * sm.max()))
    return 0


# ---------- 1. the music edit ----------
song = load(AUD / 'midnight-funk-mixkit-1147.mp3')
s = lambda t: int(round(t * SR))
XF = int(.004 * SR)                              # 4 ms each side of the splice
A = song[s(song_bar(EDIT_A[0])):s(song_bar(EDIT_A[1])) + XF].copy()
B = song[s(song_bar(EDIT_B)) - XF:].copy()
A[-2 * XF:] *= np.cos(np.linspace(0, np.pi / 2, 2 * XF))[:, None]
B[:2 * XF] *= np.sin(np.linspace(0, np.pi / 2, 2 * XF))[:, None]
N = s(DUR)
music = np.zeros((N, 2))
a0 = 0
music[a0:a0 + len(A)] += A[:N]
b0 = s(SPLICE) - XF
nb = min(len(B), N - b0)
music[b0:b0 + nb] += B[:nb]
music = fade(music, .004, .0)

# Filter dip: low-pass sweeps down over the last beat and a half before "NO", then snaps back on the hit.
d0, d1 = s(TL['dip']), s(TL['no'])
blk = int(.004 * SR)
seg = music[d0:d1]
out = np.zeros_like(seg)
zi = None
for k in range(0, len(seg), blk):
    x = (k + blk / 2) / len(seg)
    fc = 16000 * (320 / 16000) ** (x ** .6)
    sos = butter(2, fc, 'low', fs=SR, output='sos')
    if zi is None:
        zi = np.zeros((sos.shape[0], 2, 2))
    y, zi = sosfilt(sos, seg[k:k + blk], axis=0, zi=zi)
    out[k:k + blk] = y * 10 ** (-3 * x / 20)
xf = int(.003 * SR)
w = np.linspace(0, 1, xf)[:, None]
out[:xf] = seg[:xf] * (1 - w) + out[:xf] * w     # ease into the filter
music[d0:d1] = out
mus_ref = rms_db(music[s(bt(2)):s(bt(10))])       # loudness of the drop section (reference for absolute levels)


def local_db(t, half=.5):
    a, b = max(0, s(t - half)), min(N, s(t + half))
    return rms_db(music[a:b])


mix = music.copy()
log = []


def place(x, t, how, rel_db, ref=None, name=''):
    """Put sound x so its anchor lands on film time t, rel_db above the music's local RMS (or above `ref` dB)."""
    off = anchor(x, how)
    base = local_db(t) if ref is None else ref
    win = int(.3 * SR)                            # level a sound by its loudest 300 ms
    e = np.convolve((x ** 2).mean(1), np.ones(win) / win, 'valid')
    loud = 10 * np.log10(e.max() + 1e-12) if len(e) else rms_db(x)
    g = 10 ** (min(base + rel_db - loud, 18) / 20)   # cap: never lift a phone recording's noise floor more than 18 dB
    k0 = s(t) - off
    lo, hi = max(0, k0), min(N, k0 + len(x))
    if hi > lo:
        mix[lo:hi] += x[lo - k0:hi - k0] * g
    log.append((round(t, 3), name, how, round(20 * np.log10(g), 1)))


def sfx(name, dur=None):
    x = load(AUD / 'sfx' / f'{name}.mp3', 0, dur)
    return fade(x, .001, .03 if dur else .003)


# ---------- 2. the farm's own sound ----------
crow = load(FARM / 'a1593.wav', .55, 3.25)
crow = filt(filt(crow, 'high', 650), 'low', 8000)                  # removes the ~500 Hz machine hum
crow = fade(crow, .01, .5)
place(crow, .06, 'onset', +2, name='rooster crow (IMG_1593)')

flock = fade(filt(load(FARM / 'a1381.wav', 7.9, 2.2), 'high', 140), .03, .5)
place(flock, TL['drop'], 'start', -9, name='flock runs out (IMG_1381)')

clucks = fade(filt(load(FARM / 'a1151.wav', .2, .9), 'high', 160), .02, .08)
place(clucks, TL['dip'], 'start', -2, ref=mus_ref - 8, name='clucks under the filter dip (IMG_1151)')

tail = fade(filt(load(FARM / 'a1381.wav', 12.5, DUR - TL['final']), 'high', 140), .4, .6)
place(tail, TL['final'] + .25, 'start', -14, ref=mus_ref, name='flock after the last stab (IMG_1381)')

# ---------- 3. real recorded effects, sparingly ----------
place(sfx('air-woosh-quick'), TL['drop'], 'peak', -8, name='woosh into the drop')
place(sfx('bass-hit-short'), TL['drop'], 'onset', -9, name='low thump on the drop')
place(sfx('hit-blow'), TL['no'], 'onset', -5, name='hit: NO')
place(sfx('bass-hit-short'), TL['no'], 'onset', -8, name='low slam under NO')
place(sfx('swoosh-quick'), TL['antibiotics'], 'peak', -12, name='ANTIBIOTICS. rises')
place(sfx('swoosh-quick'), TL['grid'], 'peak', -10, name='grid burst')
for k in range(3):
    place(sfx('click-camera'), TL['grid'] + .08 + k * P / 2, 'onset', -15, name=f'shutter, grid ring {k}')
place(sfx('air-zoom-vacuum'), TL['mask'], 'peak', -9, name='grid collapses into NAATI')
place(sfx('whoosh-fast'), TL['brand'], 'peak', -8, name='push through the letters')
place(sfx('impact-deep-whoosh', 2.0), TL['brand'], 'onset', -9, name='brand hit')

# ---------- 4. master: -14 LUFS, oversampled limiter ----------
tmp = HERE / 'work' / 'mix_tmp.wav'
dst = HERE / 'public' / 'soundtrack.wav'


def lufs_tp(path):
    p = subprocess.run(['ffmpeg', '-nostats', '-hide_banner', '-i', str(path), '-af', 'loudnorm=print_format=json',
                        '-f', 'null', '-'], capture_output=True, text=True)
    m = json.loads(re.findall(r'\{[^{}]*"input_i"[^{}]*\}', p.stderr, re.S)[-1])
    return float(m['input_i']), float(m['input_tp'])


def master(gain_db):
    sf.write(tmp, np.clip(mix * 10 ** (gain_db / 20), -4, 4).astype(np.float32), SR, subtype='FLOAT')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(tmp), '-af',
                    'aresample=192000,alimiter=limit=0.70:attack=1.5:release=60:level=disabled,aresample=48000',
                    '-c:a', 'pcm_s24le', str(dst)], check=True)
    return lufs_tp(dst)


sf.write(tmp, mix.astype(np.float32), SR, subtype='FLOAT')
i0, _ = lufs_tp(tmp)
g = -14.0 - i0
for _ in range(3):
    i, tp = master(g)
    if abs(i + 14) < .15:
        break
    g += -14.0 - i
tmp.unlink()
(HERE / 'timeline.json').write_text(json.dumps(TL, indent=1), encoding='utf8')

print(f'{dst}: {i:.2f} LUFS, true peak {tp:.2f} dBTP (master gain {g:+.1f} dB)')
print(f'music edit: song {song_bar(EDIT_A[0]):.3f}-{song_bar(EDIT_A[1]):.3f} s + {song_bar(EDIT_B):.3f} s-end; splice at film {SPLICE:.3f} s')
for row in log:
    print('  {:7.3f}s  {:42s} {:5s} {:+.1f} dB'.format(*row[:1], row[1], row[2], row[3]))
if not (-15 <= i <= -13 and tp <= -2.0):
    sys.exit('master out of spec')
